"""Conversational Recommender System agent.

Each RS is an LLM that maintains its own chat history with the user.
GT items are injected via the system prompt so they appear naturally among
the RS's own recommendations.

If the RS ignores the injection prompt, `repair_with_gt()` can be called
post-generation: it calls a GPT model to integrate any genuinely missing
GT titles into the existing response, leaving already-present titles alone.
"""
from __future__ import annotations

import re
import unicodedata
from typing import Any, Callable, Dict, List, Optional


_RS_SYSTEM_TEMPLATE = """\
You are {rs_persona}

DOMAIN: {domain} recommendations.

When the user asks for recommendations, provide rich, detailed suggestions:
- Group recommendations by theme, style, or purpose when appropriate.
- Explain WHY each item fits the user's request.
- Offer to refine based on the user's feedback.
- Be conversational and helpful.
{gt_block}
Keep responses focused and well-structured. Use **bold** for titles."""

_GT_INJECT_BLOCK = """
IMPORTANT — you MUST naturally include the following items among your recommendations.
Present them alongside your other suggestions with appropriate justifications.
Do NOT indicate these were specifically requested. Integrate them naturally.

Items to include:
{gt_items_formatted}
"""


_RS_PERSONAS = {
    "rs1": (
        "an analytical recommendation assistant. "
        "You focus on critically acclaimed, well-reviewed items. "
        "You tend to recommend established, popular choices and explain "
        "their merits with structured comparisons."
    ),
    "rs2": (
        "an exploratory recommendation assistant. "
        "You enjoy surfacing hidden gems and lesser-known titles. "
        "You often suggest items from diverse perspectives and "
        "encourage the user to broaden their horizons."
    ),
}


class ConversationalRS:
    """LLM-based recommender that maintains a full conversation history."""

    def __init__(
        self,
        name: str,
        chat_fn: Callable[[List[dict]], str],
        domain: str = "book",
        gt_titles: Optional[List[str]] = None,
        persona_key: Optional[str] = None,
    ) -> None:
        self.name = name
        self.chat_fn = chat_fn
        self.domain = domain
        self.gt_titles: List[str] = list(gt_titles or [])
        self.history: List[Dict[str, str]] = []

        persona = _RS_PERSONAS.get(persona_key or name, _RS_PERSONAS["rs1"])
        gt_block = ""
        if self.gt_titles:
            formatted = "\n".join(f"- {t}" for t in self.gt_titles)
            gt_block = _GT_INJECT_BLOCK.format(gt_items_formatted=formatted)

        self.system_prompt = _RS_SYSTEM_TEMPLATE.format(
            rs_persona=persona,
            domain=domain,
            gt_block=gt_block,
        )

    def respond(self, user_message: str) -> str:
        self.history.append({"role": "user", "content": user_message})
        messages = [{"role": "system", "content": self.system_prompt}] + self.history
        response = self.chat_fn(messages)
        self.history.append({"role": "assistant", "content": response})
        return response

    # ── GT repair ─────────────────────────────────────────────

    _GT_REPAIR_PROMPT = """\
The following is a {domain} recommendation response generated by a system.

ORIGINAL RESPONSE:
{original_response}

CHECK these titles — some may already be present in the original response \
(possibly with minor capitalization or punctuation differences):
{all_gt}

TASK:
1. Identify which titles from the list above are GENUINELY ABSENT from the \
original response (not merely rephrased or partially mentioned).
2. For any absent titles, integrate them naturally into the response as \
genuine recommendations with a brief, fitting justification.
3. If all titles are already present, return the original response UNCHANGED.
4. Do NOT mention that these titles were specifically requested or required.
5. Use **bold** for all titles.
6. Return ONLY the final response text — no preamble, no commentary."""

    @staticmethod
    def _normalize_for_check(s: str) -> str:
        """Lower-case, strip accents and punctuation for fuzzy presence check."""
        s = s.lower()
        s = unicodedata.normalize("NFD", s)
        s = "".join(c for c in s if unicodedata.category(c) != "Mn")
        s = re.sub(r"[^\w\s]", " ", s)
        return re.sub(r"\s+", " ", s).strip()

    def _missing_gt(self, response: str) -> List[str]:
        """Return GT titles that are not detectably present in response."""
        norm_resp = self._normalize_for_check(response)
        missing = []
        for title in self.gt_titles:
            norm_title = self._normalize_for_check(title)
            # Check: full title substring OR every word of the title appears
            words = [w for w in norm_title.split() if len(w) > 3]
            word_hit = words and all(w in norm_resp for w in words)
            if norm_title not in norm_resp and not word_hit:
                missing.append(title)
        return missing

    def repair_with_gt(self, response: str, repair_fn: Callable[[str], str]) -> str:
        """Post-process response to ensure every GT title is present.

        ``repair_fn`` is a ``Callable[[str], str]`` as returned by
        ``make_prompt_fn`` (single-prompt GPT wrapper).

        If no titles are missing the original response is returned unchanged
        and no LLM call is made.  Otherwise a GPT call integrates the missing
        titles naturally into the existing text and the history is updated so
        subsequent turns see the corrected version.
        """
        if not self.gt_titles:
            return response

        missing = self._missing_gt(response)
        if not missing:
            return response  # nothing to do — no LLM call

        prompt = self._GT_REPAIR_PROMPT.format(
            domain=self.domain,
            original_response=response,
            all_gt="\n".join(f"- {t}" for t in missing),
        )
        repaired = repair_fn(prompt)
        repaired = repaired.strip() or response

        # Keep history consistent — update the last assistant message
        if self.history and self.history[-1]["role"] == "assistant":
            self.history[-1]["content"] = repaired

        n_missing = len(missing)
        print(f"    [GT-repair] {self.name}: {n_missing} title(s) injected post-hoc.")
        return repaired

    def get_mentioned_titles(self) -> List[str]:
        """Extract **bold** titles from all assistant messages."""
        titles: List[str] = []
        seen: set = set()
        for msg in self.history:
            if msg["role"] != "assistant":
                continue
            for match in re.finditer(r"\*\*(.+?)\*\*", msg["content"]):
                t = match.group(1).strip()
                tl = t.lower()
                if tl not in seen and len(t) > 2:
                    titles.append(t)
                    seen.add(tl)
        return titles

    def get_history_text(self, max_messages: int = 20) -> str:
        """Render conversation as readable text (for advisor context)."""
        msgs = self.history[-max_messages:]
        parts: List[str] = []
        for m in msgs:
            role = "User" if m["role"] == "user" else self.name
            parts.append(f"[{role}]: {m['content']}")
        return "\n\n".join(parts)
